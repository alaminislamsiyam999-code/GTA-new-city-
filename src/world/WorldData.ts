export function getTerrainElevation(x: number, z: number): number {
  // Ocean bed south of shoreline
  if (z > 472) {
    return -2.2;
  }
  // Beach gentle slope (z = 420..472)
  if (z > 420) {
    const t = (z - 420) / 52;
    return Math.max(-1.8, (1 - t) * 0.1 - t * 1.4);
  }
  // Sierra Vista Mountains in North (z < -385)
  if (z < -385) {
    const northDist = Math.min(1, (-385 - z) / 220);
    // Keep central scenic road passable with smooth grade up to overlook at (0, -460)
    const ridge = Math.sin(x * 0.014) * 5.5 + Math.cos(z * 0.02) * 3.5;
    return Math.max(0, northDist * 22 + ridge * northDist);
  }
  // Emerald River channel (x = 296..324, except highway bridges around z = -240,-120,0,120,240,360)
  if (x > 296 && x < 324 && z > -385 && z <= 420) {
    const onBridge = ROAD_COORDS.some((rz) => Math.abs(z - rz) < 13.5);
    if (!onBridge) {
      return -1.75;
    }
  }
  return 0;
}

export function getDistrictAt(x: number, z: number): DistrictZone {
  for (const d of DISTRICTS) {
    if (x >= d.minX && x <= d.maxX && z >= d.minZ && z <= d.maxZ) {
      return d;
    }
  }
  return DISTRICTS[0];
}
